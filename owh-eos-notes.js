    <div class="owh-eos-model">
<p data-eos-tone="strength"><strong>S1 — Depth of the case study.</strong> The clinicians could
compare ADIS-C/P accounts from the boy and his mother with his actions
during exposure. By session four he could complete the in-vivo tasks,
but his distress had risen. Together these measures showed why being
able to touch buttons was not sufficient evidence that his phobia had
resolved.</p>
<p data-eos-tone="strength"><strong>S2 — Follow-up.</strong> The child and parent interview
schedule was readministered at six and twelve months. The boy was still
wearing clear plastic buttons on his school uniform, rather than merely
tolerating them once in the clinic. These outcomes support maintenance
in this case beyond the immediate treatment period.</p>
<p data-eos-tone="limitation"><strong>W1 — Subjective data.</strong> The distress scores relied on
a nine-year-old interpreting the 0–8 Feelings Thermometer. For example,
he may have reported a lower score after imagining buttons falling over
him because he wanted to appear braver, not because disgust had fallen
as much. This limits the validity of the scores as measures of the
actual size of the change.</p>
<p data-eos-tone="limitation"><strong>W2 — No component control.</strong> Imagery and cognitive
restructuring were added after rewarded live exposure; no comparable
child received live exposure alone. Improvement afterward could partly
reflect earlier practice or the combined programme. Consequently the
case cannot establish that imagery alone produced the lasting
change.</p>
</div>
