    <ul>
<li><strong>Nurture:</strong> An association developed after the
classroom incident and reactions changed with treatment. It does not
rule out individual sensitivity. <strong>Application:</strong> For a
similar patient, ask what makes the stimulus disgusting rather than
assume fear is the only barrier.</li>
<li><strong>Quick recall:</strong> Why did completing every item not
prove treatment success? What did <strong>8 → 5 → 3</strong> measure?
Which two follow-up times show maintenance?</li>
</ul>
